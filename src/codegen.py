# src/codegen.py
# High-Performance C99 / LLVM-ready Code Generator for Katlin

from typing import List, Dict, Optional, Tuple, Any
from src.ast_nodes import (
    Program, FunctionDef, Parameter, VarDecl, AssignStmt, ReturnStmt, BreakStmt, ContinueStmt,
    PrintStmt, CallExpr, ChainedCall, IfStmt, WhileStmt, LoopStmt, ForStmt,
    RawBlock, BinaryOp, UnaryOp, Literal, Identifier, ExprStmt, IndexAssign, IndexExpr,
    StructField, StructDef, StructInit, MemberAccess, EnumDef, OrExpr, MatchBranch, MatchStmt, TestBlock, ASTNode
)

TYPE_MAP = {
    "int": "ktl_int",
    "str": "ktl_str",
    "bool": "ktl_bool",
    "float": "ktl_float",
    "i64": "ktl_i64",
    "u64": "ktl_u64",
    "byte": "ktl_byte",
    "vec": "ktl_vec",
    "arena": "ktl_arena",
    "sb": "ktl_sb",
}

class CodeGenerator:
    def __init__(self, program: Program, test_mode: bool = False):
        self.program = program
        self.test_mode = test_mode
        self.indent_level = 0
        self.output: List[str] = []
        self.symbol_types: Dict[str, str] = {}
        self.struct_fields: Dict[str, Dict[str, str]] = {}
        self.struct_field_refs: Dict[str, Dict[str, bool]] = {}
        self.enums: Dict[str, List[str]] = {}
        self.functions: Dict[str, FunctionDef] = {}
        self.current_func: Optional[FunctionDef] = None
        self.ref_params: set = set()
        self.chain_var_counter = 0

    def indent(self) -> str:
        return "    " * self.indent_level

    def emit(self, line: str = ""):
        if line:
            self.output.append(f"{self.indent()}{line}")
        else:
            self.output.append("")

    def to_ptr(self, code: str) -> str:
        clean = code.strip()
        if clean in self.ref_params or clean.startswith("&") or clean.startswith("*"):
            return clean
        return f"&{clean}"

    def generate(self) -> str:
        # Pre-scan functions, enums, structs
        for stmt in self.program.statements:
            if isinstance(stmt, FunctionDef):
                self.functions[stmt.name] = stmt
            elif isinstance(stmt, EnumDef):
                self.enums[stmt.name] = stmt.variants
            elif isinstance(stmt, StructDef):
                self.struct_fields[stmt.name] = { f.name: f.type_name for f in stmt.fields }
                self.struct_field_refs[stmt.name] = { f.name: f.is_ref for f in stmt.fields }

        # Headers
        self.emit("// Generated by Katlin Compiler (Native C99 / LLVM Backend)")
        self.emit('#include "katlin_runtime.h"')
        self.emit()

        # Emit Enums
        for stmt in self.program.statements:
            if isinstance(stmt, EnumDef):
                self.emit(f"typedef enum {stmt.name} {stmt.name};")
                self.emit(f"enum {stmt.name} {{")
                self.indent_level += 1
                for v in stmt.variants:
                    self.emit(f"{stmt.name}_{v},")
                self.indent_level -= 1
                self.emit("};")
                self.emit()

        # Emit Structs
        for stmt in self.program.statements:
            if isinstance(stmt, StructDef):
                self.emit(f"typedef struct {stmt.name} {stmt.name};")
                self.emit(f"struct {stmt.name} {{")
                self.indent_level += 1
                for f in stmt.fields:
                    f_type = TYPE_MAP.get(f.type_name, f.type_name)
                    if f.is_ref:
                        f_type += "*"
                    self.emit(f"{f_type} {f.name};")
                self.indent_level -= 1
                self.emit("};")
                self.emit()

        # Generate Context Structs and Function Signatures for Functions with Inner Functions
        for func in self.functions.values():
            if func.inner_functions:
                self.generate_context_struct(func)

        # Forward declarations of standard functions
        for func in self.functions.values():
            if func.name != "main" and not func.inner_functions:
                ret_type = TYPE_MAP.get(func.return_type, func.return_type) if func.return_type else "void"
                params_str = self.generate_params(func.params)
                self.emit(f"static {ret_type} {func.name}({params_str});")
            elif func.name == "main" and self.test_mode:
                self.emit("static int ktl_user_main(int argc, char** argv);")

        self.emit()

        # Generate Function Bodies
        for stmt in self.program.statements:
            if isinstance(stmt, FunctionDef):
                self.generate_function(stmt)
            elif not isinstance(stmt, TestBlock):
                self.generate_statement(stmt)

        # Generate Test Runner if in test_mode
        test_blocks = [s for s in self.program.statements if isinstance(s, TestBlock)]
        if self.test_mode:
            self.emit()
            self.emit("// -------------------------------------------------------------")
            self.emit("// Katlin Test Suite Runner")
            self.emit("// -------------------------------------------------------------")
            for idx, tb in enumerate(test_blocks):
                self.emit(f"static void ktl_test_{idx}(void) {{")
                self.indent_level += 1
                for s in tb.body:
                    self.generate_statement(s)
                self.indent_level -= 1
                self.emit("}")
                self.emit()

            self.emit("int main(int argc, char** argv) {")
            self.indent_level += 1
            self.emit('printf("\\n=== KATLIN TEST RUNNER ===\\n\\n");')
            self.emit("double _all_start = ktl_time_now();")
            self.emit("int _passed = 0;")
            self.emit(f"int _total = {len(test_blocks)};")
            self.emit()
            for idx, tb in enumerate(test_blocks):
                clean_name = tb.name.replace('"', '\\"')
                self.emit("{")
                self.indent_level += 1
                self.emit(f'printf("  test \\"%s\\"... ", "{clean_name}");')
                self.emit("fflush(stdout);")
                self.emit("double _t0 = ktl_time_now();")
                self.emit(f"ktl_test_{idx}();")
                self.emit('printf("ok (%.6fs)\\n", ktl_time_now() - _t0);')
                self.emit("_passed++;")
                self.indent_level -= 1
                self.emit("}")
            self.emit()
            self.emit('printf("\\nTest results: %d passed, 0 failed (total: %.4fs)\\n\\n", _passed, ktl_time_now() - _all_start);')
            self.emit("return 0;")
            self.indent_level -= 1
            self.emit("}")

        return "\n".join(self.output)

    def generate_context_struct(self, func: FunctionDef):
        struct_name = f"{func.name}_ctx"
        self.emit(f"typedef struct {struct_name} {struct_name};")
        self.emit(f"struct {struct_name} {{")
        self.indent_level += 1

        # Collect all local vars in func.body to become struct fields
        fields: Dict[str, str] = {}
        for p in func.params:
            fields[p.name] = TYPE_MAP.get(p.type_name, "ktl_int")
        for s in func.body:
            if isinstance(s, VarDecl):
                t = TYPE_MAP.get(s.type_name, "ktl_int") if s.type_name else "ktl_int"
                fields[s.name] = t

        for f_name, f_type in fields.items():
            self.emit(f"{f_type} {f_name};")

        self.indent_level -= 1
        self.emit("};")
        self.emit()

        # Constructor function
        params_str = self.generate_params(func.params)
        self.emit(f"static inline {struct_name} {func.name}({params_str}) {{")
        self.indent_level += 1
        self.emit(f"{struct_name} _self;")
        # Assign parameter defaults / values
        for p in func.params:
            self.emit(f"_self.{p.name} = {p.name};")
        
        # Execute any initial assignments in func body
        for s in func.body:
            if isinstance(s, VarDecl) and s.value:
                val_code = self.generate_expr(s.value)
                # If value is referencing another field, prefix with _self.
                for p in func.params:
                    if p.name == val_code:
                        val_code = f"_self.{p.name}"
                self.emit(f"_self.{s.name} = {val_code};")

        self.emit("return _self;")
        self.indent_level -= 1
        self.emit("}")
        self.emit()

        # Generate methods for inner functions
        for inner in func.inner_functions:
            ret_type = TYPE_MAP.get(inner.return_type, "void") if inner.return_type else f"{struct_name}*"
            method_params = [f"{struct_name}* _self"]
            for p in inner.params:
                p_type = TYPE_MAP.get(p.type_name, "ktl_int")
                method_params.append(f"{p_type} {p.name}")
            
            p_str = ", ".join(method_params)
            method_c_name = f"{func.name}_{inner.name}"
            self.emit(f"static inline {ret_type} {method_c_name}({p_str}) {{")
            self.indent_level += 1
            
            # Map struct fields inside inner function body
            old_symbols = dict(self.symbol_types)
            for f_name, f_type in fields.items():
                self.symbol_types[f_name] = f_type
            
            for s in inner.body:
                self.generate_statement(s, context_prefix="_self->", valid_fields=fields)

            self.symbol_types = old_symbols

            if not inner.return_type:
                self.emit("return _self;")
            self.indent_level -= 1
            self.emit("}")
            self.emit()

    def generate_params(self, params: List[Parameter]) -> str:
        if not params:
            return "void"
        parts = []
        for p in params:
            c_type = TYPE_MAP.get(p.type_name, p.type_name)
            if p.is_ref:
                c_type += "*"
            parts.append(f"{c_type} {p.name}")
            self.symbol_types[p.name] = p.type_name
        return ", ".join(parts)

    def generate_function(self, func: FunctionDef):
        # Skip if this function has inner functions (handled as context struct above)
        if func.inner_functions:
            return

        self.current_func = func
        self.ref_params = {p.name for p in func.params if p.is_ref}
        is_main = (func.name == "main")
        ret_type = "int" if is_main else (TYPE_MAP.get(func.return_type, func.return_type) if func.return_type else "void")
        params_str = "int argc, char** argv" if is_main else self.generate_params(func.params)

        if is_main and self.test_mode:
            sig = f"static int ktl_user_main({params_str})"
        elif is_main:
            sig = f"int main({params_str})"
        else:
            sig = f"static {ret_type} {func.name}({params_str})"
        self.emit(f"{sig} {{")
        self.indent_level += 1
        if is_main:
            self.emit("ktl_init_args(argc, argv);")

        for i, stmt in enumerate(func.body):
            # If function returns a value and last statement is an ExprStmt, emit as return
            if not is_main and func.return_type and func.return_type != "void" and i == len(func.body) - 1 and isinstance(stmt, ExprStmt):
                expr_code = self.generate_expr(stmt.expr)
                self.emit(f"return {expr_code};")
            else:
                self.generate_statement(stmt)

        if is_main:
            self.emit("return 0;")

        self.indent_level -= 1
        self.emit("}")
        self.emit()
        self.current_func = None

    def infer_expr_type(self, expr: Optional[ASTNode]) -> str:
        if not expr:
            return "int"
        if isinstance(expr, Literal):
            return expr.lit_type
        if isinstance(expr, Identifier):
            return self.symbol_types.get(expr.name, "int")
        if isinstance(expr, CallExpr):
            if expr.callee in ("time_now", "get_ram_mb"):
                return "float"
            if expr.callee in ("file_read", "str_concat", "args_get", "str_sub", "str_from_char", "str_int", "path_base", "path_dir", "sb_build"):
                return "str"
            if expr.callee in ("file_write", "file_append", "file_exists", "str_eq", "assert", "str_starts_with", "str_ends_with", "str_contains"):
                return "bool"
            if expr.callee in ("vec_get",):
                return "i64"
            if expr.callee in ("str_len", "str_char_at", "str_index_of", "parse_int", "args_count", "system", "math_abs", "abs", "math_min", "min", "math_max", "max", "vec_len", "alloc_ints"):
                return "int"
            if expr.callee == "vec_create":
                return "vec"
            if expr.callee == "arena_create":
                return "arena"
            if expr.callee == "sb_create":
                return "sb"
            # User-defined functions: resolve the declared return type. Without
            # this every call to a project-local function fell through to the
            # "int" guess below, which silently picked the wrong printf
            # specifier for `str`/`float` returns and printed garbage.
            target = self.functions.get(expr.callee)
            if target is not None and target.return_type:
                return target.return_type
            return "int"
        if isinstance(expr, BinaryOp):
            l_t = self.infer_expr_type(expr.left)
            r_t = self.infer_expr_type(expr.right)
            if "float" in (l_t, r_t):
                return "float"
            if "i64" in (l_t, r_t) or "u64" in (l_t, r_t):
                return "i64"
            return l_t
        if isinstance(expr, MemberAccess):
            if isinstance(expr.target, Identifier) and expr.target.name in self.enums:
                return expr.target.name
            if isinstance(expr.target, Identifier):
                tgt_type = self.symbol_types.get(expr.target.name)
                if tgt_type and tgt_type in self.struct_fields:
                    return self.struct_fields[tgt_type].get(expr.member, "int")
            if expr.member in ("name", "msg", "title", "text", "path", "url"):
                return "str"
        return "int"

    def generate_statement(self, stmt: ASTNode, context_prefix: str = "", valid_fields: Optional[Dict[str, str]] = None):
        if isinstance(stmt, ReturnStmt):
            val_code = self.generate_expr(stmt.value, context_prefix, valid_fields) if stmt.value else ""
            if self.current_func and self.current_func.name == "main" and not val_code:
                val_code = "0"
            if stmt.guard_condition:
                cond_code = self.generate_expr(stmt.guard_condition, context_prefix, valid_fields)
                if val_code:
                    self.emit(f"if ({cond_code}) return {val_code};")
                else:
                    self.emit(f"if ({cond_code}) return;")
            else:
                if val_code:
                    self.emit(f"return {val_code};")
                else:
                    self.emit("return;")

        elif isinstance(stmt, BreakStmt):
            self.emit("break;")

        elif isinstance(stmt, ContinueStmt):
            self.emit("continue;")

        elif isinstance(stmt, PrintStmt):
            self.generate_print(stmt, context_prefix, valid_fields)

        elif isinstance(stmt, VarDecl):
            val_code = self.generate_expr(stmt.value, context_prefix, valid_fields) if stmt.value else "0"
            if stmt.is_inferred:
                c_type = "__auto_type"
                if isinstance(stmt.value, StructInit):
                    inferred_type = stmt.value.struct_name
                else:
                    inferred_type = self.infer_expr_type(stmt.value)
            else:
                c_type = TYPE_MAP.get(stmt.type_name, stmt.type_name)
                inferred_type = stmt.type_name or "int"
            
            # Store in symbol table
            self.symbol_types[stmt.name] = inferred_type

            # If not mutable and not inferred, make it const
            const_kw = "" if stmt.is_mutable else "const "
            self.emit(f"{const_kw}{c_type} {stmt.name} = {val_code};")

        elif isinstance(stmt, AssignStmt):
            val_code = self.generate_expr(stmt.value, context_prefix, valid_fields)
            if isinstance(stmt.target, ASTNode):
                target = self.generate_expr(stmt.target, context_prefix, valid_fields)
            else:
                target = str(stmt.target)
                if valid_fields and target in valid_fields:
                    target = f"{context_prefix}{target}"
            self.emit(f"{target} {stmt.op} {val_code};")

        elif isinstance(stmt, IndexAssign):
            idx_code = self.generate_expr(stmt.index, context_prefix, valid_fields)
            val_code = self.generate_expr(stmt.value, context_prefix, valid_fields)
            target = stmt.target
            if valid_fields and target in valid_fields:
                target = f"{context_prefix}{target}"
            self.emit(f"{target}[{idx_code}] {stmt.op} {val_code};")

        elif isinstance(stmt, IfStmt):
            cond_code = self.generate_expr(stmt.condition, context_prefix, valid_fields)
            self.emit(f"if ({cond_code}) {{")
            self.indent_level += 1
            for s in stmt.then_body:
                self.generate_statement(s, context_prefix, valid_fields)
            self.indent_level -= 1

            for elif_cond, elif_body in stmt.elif_branches:
                e_cond = self.generate_expr(elif_cond, context_prefix, valid_fields)
                self.emit(f"}} else if ({e_cond}) {{")
                self.indent_level += 1
                for s in elif_body:
                    self.generate_statement(s, context_prefix, valid_fields)
                self.indent_level -= 1

            if stmt.else_body:
                self.emit("} else {")
                self.indent_level += 1
                for s in stmt.else_body:
                    self.generate_statement(s, context_prefix, valid_fields)
                self.indent_level -= 1

            self.emit("}")

        elif isinstance(stmt, WhileStmt):
            cond_code = self.generate_expr(stmt.condition, context_prefix, valid_fields)
            self.emit(f"while ({cond_code}) {{")
            self.indent_level += 1
            for s in stmt.body:
                self.generate_statement(s, context_prefix, valid_fields)
            self.indent_level -= 1
            self.emit("}")

        elif isinstance(stmt, LoopStmt):
            self.emit("while (1) {")
            self.indent_level += 1
            for s in stmt.body:
                self.generate_statement(s, context_prefix, valid_fields)
            self.indent_level -= 1
            self.emit("}")

        elif isinstance(stmt, ForStmt):
            start_code = self.generate_expr(stmt.range_start, context_prefix, valid_fields)
            end_code = self.generate_expr(stmt.range_end, context_prefix, valid_fields)
            step_code = self.generate_expr(stmt.step, context_prefix, valid_fields) if stmt.step else "1"
            self.symbol_types[stmt.var_name] = "int"
            
            if stmt.step:
                self.emit(f"for (ktl_int {stmt.var_name} = {start_code}; {stmt.var_name} < {end_code}; {stmt.var_name} += {step_code}) {{")
            else:
                self.emit(f"for (ktl_int {stmt.var_name} = {start_code}; {stmt.var_name} < {end_code}; {stmt.var_name}++) {{")
            
            self.indent_level += 1
            for s in stmt.body:
                self.generate_statement(s, context_prefix, valid_fields)
            self.indent_level -= 1
            self.emit("}")

        elif isinstance(stmt, MatchStmt):
            subj_code = self.generate_expr(stmt.subject, context_prefix, valid_fields)
            subj_type = None
            if isinstance(stmt.subject, Identifier):
                subj_type = self.symbol_types.get(stmt.subject.name)
            self.emit(f"switch ({subj_code}) {{")
            self.indent_level += 1
            for b in stmt.branches:
                pat = b.pattern
                if pat == "_":
                    self.emit("default: {")
                else:
                    clean_pat = pat.lstrip(".")
                    if subj_type and subj_type in self.enums:
                        clean_pat = f"{subj_type}_{clean_pat}"
                    self.emit(f"case {clean_pat}: {{")
                self.indent_level += 1
                for s in b.body:
                    self.generate_statement(s, context_prefix, valid_fields)
                self.emit("break;")
                self.indent_level -= 1
                self.emit("}")
            self.indent_level -= 1
            self.emit("}")

        elif isinstance(stmt, RawBlock):
            self.emit("// [raw] Bare-Metal Block")
            for s in stmt.body:
                self.generate_statement(s, context_prefix, valid_fields)

        elif isinstance(stmt, ExprStmt):
            expr_code = self.generate_expr(stmt.expr, context_prefix, valid_fields)
            self.emit(f"{expr_code};")

    def generate_print(self, stmt: PrintStmt, context_prefix: str = "", valid_fields: Optional[Dict[str, str]] = None):
        fmt = stmt.format_str
        nl = "\\n" if stmt.is_newline else ""

        # Replace '%' with appropriate specifiers based on argument types
        arg_codes = []
        fmt_parts = fmt.split("%")
        new_fmt = fmt_parts[0]

        for i, arg in enumerate(stmt.args):
            arg_code = self.generate_expr(arg, context_prefix, valid_fields)
            # Determine format specifier
            spec = "%d"
            if isinstance(arg, Literal):
                if arg.lit_type == "str": spec = "%s"
                elif arg.lit_type == "float": spec = "%g"
                elif arg.lit_type == "bool":
                    spec = "%s"
                    arg_code = f"({arg_code} ? \"true\" : \"false\")"
            elif isinstance(arg, Identifier):
                var_t = self.symbol_types.get(arg.name, "int")
                if var_t in ("str", "ktl_str"): spec = "%s"
                elif var_t in ("float", "ktl_float", "f64", "ktl_f64"): spec = "%f"
                elif var_t in ("i64", "ktl_i64", "u64", "ktl_u64"):
                    spec = "%lld"
                    arg_code = f"((long long)({arg_code}))"
                elif var_t in ("bool", "ktl_bool"):
                    spec = "%s"
                    arg_code = f"({arg_code} ? \"true\" : \"false\")"
            else:
                expr_t = self.infer_expr_type(arg)
                if expr_t in ("float", "ktl_float", "f64", "ktl_f64"): spec = "%f"
                elif expr_t in ("i64", "ktl_i64", "u64", "ktl_u64"):
                    spec = "%lld"
                    arg_code = f"((long long)({arg_code}))"
                elif expr_t in ("str", "ktl_str"): spec = "%s"
                elif expr_t in ("bool", "ktl_bool"):
                    spec = "%s"
                    arg_code = f"({arg_code} ? \"true\" : \"false\")"
                else:
                    spec = "%d"
            
            arg_codes.append(arg_code)
            new_fmt += spec
            if i + 1 < len(fmt_parts):
                new_fmt += fmt_parts[i + 1]

        # Escape newlines and ANSI escapes
        new_fmt += nl
        new_fmt_clean = new_fmt.replace("\n", "\\n").replace("\r", "\\r").replace("\t", "\\t").replace("\x1b", "\\033")

        if arg_codes:
            args_str = ", ".join(arg_codes)
            self.emit(f'printf("{new_fmt_clean}", {args_str});')
        else:
            self.emit(f'printf("{new_fmt_clean}");')

    def generate_expr(self, expr: ASTNode, context_prefix: str = "", valid_fields: Optional[Dict[str, str]] = None) -> str:
        if isinstance(expr, Literal):
            if expr.lit_type == "str":
                clean_val = str(expr.value).replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n').replace('\r', '\\r').replace('\t', '\\t').replace('\x1b', '\\033')
                return f'"{clean_val}"'
            if expr.lit_type == "bool":
                return "true" if expr.value else "false"
            return str(expr.value)

        if isinstance(expr, Identifier):
            name = expr.name
            if valid_fields and name in valid_fields:
                return f"{context_prefix}{name}"
            return name

        if isinstance(expr, BinaryOp):
            l = self.generate_expr(expr.left, context_prefix, valid_fields)
            r = self.generate_expr(expr.right, context_prefix, valid_fields)
            return f"({l} {expr.op} {r})"

        if isinstance(expr, UnaryOp):
            opnd = self.generate_expr(expr.operand, context_prefix, valid_fields)
            return f"{expr.op}({opnd})"

        if isinstance(expr, IndexExpr):
            target_code = self.generate_expr(expr.target, context_prefix, valid_fields)
            idx_code = self.generate_expr(expr.index, context_prefix, valid_fields)
            return f"{target_code}[{idx_code}]"

        if isinstance(expr, CallExpr):
            if expr.callee == "time_now":
                return "ktl_time_now()"
            if expr.callee == "get_ram_mb":
                return "ktl_get_ram_mb()"
            if expr.callee == "alloc_ints":
                arg_code = self.generate_expr(expr.args[0], context_prefix, valid_fields)
                return f"ktl_alloc_ints({arg_code})"
            if expr.callee == "free_ints":
                arg_code = self.generate_expr(expr.args[0], context_prefix, valid_fields)
                return f"ktl_free_ints({arg_code})"
            if expr.callee == "arena_create":
                cap = self.generate_expr(expr.args[0], context_prefix, valid_fields)
                return f"ktl_arena_create({cap})"
            if expr.callee == "arena_alloc":
                a = self.generate_expr(expr.args[0], context_prefix, valid_fields)
                sz = self.generate_expr(expr.args[1], context_prefix, valid_fields)
                return f"ktl_arena_alloc({self.to_ptr(a)}, {sz})"
            if expr.callee == "arena_reset":
                a = self.generate_expr(expr.args[0], context_prefix, valid_fields)
                return f"ktl_arena_reset({self.to_ptr(a)})"
            if expr.callee == "arena_destroy":
                a = self.generate_expr(expr.args[0], context_prefix, valid_fields)
                return f"ktl_arena_destroy({self.to_ptr(a)})"
            if expr.callee == "panic":
                msg = self.generate_expr(expr.args[0], context_prefix, valid_fields)
                return f"ktl_panic({msg})"
            if expr.callee == "assert":
                cond = self.generate_expr(expr.args[0], context_prefix, valid_fields)
                msg = self.generate_expr(expr.args[1], context_prefix, valid_fields) if len(expr.args) > 1 else '"assertion failed"'
                return f"ktl_assert({cond}, {msg})"
            if expr.callee == "file_exists":
                path = self.generate_expr(expr.args[0], context_prefix, valid_fields)
                return f"ktl_file_exists({path})"
            if expr.callee == "file_read":
                path = self.generate_expr(expr.args[0], context_prefix, valid_fields)
                return f"ktl_file_read_str({path})"
            if expr.callee == "file_write":
                path = self.generate_expr(expr.args[0], context_prefix, valid_fields)
                content = self.generate_expr(expr.args[1], context_prefix, valid_fields)
                return f"ktl_file_write_str({path}, {content})"
            if expr.callee == "file_append":
                path = self.generate_expr(expr.args[0], context_prefix, valid_fields)
                content = self.generate_expr(expr.args[1], context_prefix, valid_fields)
                return f"ktl_file_append_str({path}, {content})"
            if expr.callee == "str_len":
                s = self.generate_expr(expr.args[0], context_prefix, valid_fields)
                return f"ktl_str_len({s})"
            if expr.callee == "str_eq":
                a = self.generate_expr(expr.args[0], context_prefix, valid_fields)
                b = self.generate_expr(expr.args[1], context_prefix, valid_fields)
                return f"ktl_str_eq({a}, {b})"
            if expr.callee == "str_concat":
                a = self.generate_expr(expr.args[0], context_prefix, valid_fields)
                b = self.generate_expr(expr.args[1], context_prefix, valid_fields)
                return f"ktl_str_concat({a}, {b})"
            if expr.callee in ("abs", "math_abs"):
                x = self.generate_expr(expr.args[0], context_prefix, valid_fields)
                return f"ktl_math_abs({x})"
            if expr.callee in ("min", "math_min"):
                a = self.generate_expr(expr.args[0], context_prefix, valid_fields)
                b = self.generate_expr(expr.args[1], context_prefix, valid_fields)
                return f"ktl_math_min({a}, {b})"
            if expr.callee in ("max", "math_max"):
                a = self.generate_expr(expr.args[0], context_prefix, valid_fields)
                b = self.generate_expr(expr.args[1], context_prefix, valid_fields)
                return f"ktl_math_max({a}, {b})"
            if expr.callee == "vec_create":
                cap = self.generate_expr(expr.args[0], context_prefix, valid_fields) if expr.args else "8"
                return f"ktl_vec_create({cap})"
            if expr.callee == "vec_push":
                v = self.generate_expr(expr.args[0], context_prefix, valid_fields)
                item = self.generate_expr(expr.args[1], context_prefix, valid_fields)
                return f"ktl_vec_push({self.to_ptr(v)}, {item})"
            if expr.callee == "vec_get":
                v = self.generate_expr(expr.args[0], context_prefix, valid_fields)
                idx = self.generate_expr(expr.args[1], context_prefix, valid_fields)
                return f"ktl_vec_get({self.to_ptr(v)}, {idx})"
            if expr.callee == "vec_set":
                v = self.generate_expr(expr.args[0], context_prefix, valid_fields)
                idx = self.generate_expr(expr.args[1], context_prefix, valid_fields)
                val = self.generate_expr(expr.args[2], context_prefix, valid_fields)
                return f"ktl_vec_set({self.to_ptr(v)}, {idx}, {val})"
            if expr.callee == "vec_len":
                v = self.generate_expr(expr.args[0], context_prefix, valid_fields)
                return f"ktl_vec_len({self.to_ptr(v)})"
            if expr.callee == "vec_free":
                v = self.generate_expr(expr.args[0], context_prefix, valid_fields)
                return f"ktl_vec_free({self.to_ptr(v)})"
            if expr.callee == "args_count":
                return "ktl_args_count()"
            if expr.callee == "args_get":
                idx = self.generate_expr(expr.args[0], context_prefix, valid_fields)
                return f"ktl_args_get({idx})"
            if expr.callee == "system":
                cmd = self.generate_expr(expr.args[0], context_prefix, valid_fields)
                return f"ktl_system({cmd})"
            if expr.callee == "str_char_at":
                s = self.generate_expr(expr.args[0], context_prefix, valid_fields)
                idx = self.generate_expr(expr.args[1], context_prefix, valid_fields)
                return f"ktl_str_char_at({s}, {idx})"
            if expr.callee == "str_sub":
                s = self.generate_expr(expr.args[0], context_prefix, valid_fields)
                start = self.generate_expr(expr.args[1], context_prefix, valid_fields)
                length = self.generate_expr(expr.args[2], context_prefix, valid_fields)
                return f"ktl_str_sub({s}, {start}, {length})"
            if expr.callee == "str_from_char":
                c = self.generate_expr(expr.args[0], context_prefix, valid_fields)
                return f"ktl_str_from_char({c})"
            if expr.callee == "str_starts_with":
                s = self.generate_expr(expr.args[0], context_prefix, valid_fields)
                p = self.generate_expr(expr.args[1], context_prefix, valid_fields)
                return f"ktl_str_starts_with({s}, {p})"
            if expr.callee == "str_ends_with":
                s = self.generate_expr(expr.args[0], context_prefix, valid_fields)
                p = self.generate_expr(expr.args[1], context_prefix, valid_fields)
                return f"ktl_str_ends_with({s}, {p})"
            if expr.callee == "str_index_of":
                s = self.generate_expr(expr.args[0], context_prefix, valid_fields)
                needle = self.generate_expr(expr.args[1], context_prefix, valid_fields)
                start = self.generate_expr(expr.args[2], context_prefix, valid_fields) if len(expr.args) > 2 else "0"
                return f"ktl_str_index_of({s}, {needle}, {start})"
            if expr.callee == "str_contains":
                s = self.generate_expr(expr.args[0], context_prefix, valid_fields)
                needle = self.generate_expr(expr.args[1], context_prefix, valid_fields)
                return f"ktl_str_contains({s}, {needle})"
            if expr.callee == "str_int":
                val = self.generate_expr(expr.args[0], context_prefix, valid_fields)
                return f"ktl_str_int({val})"
            if expr.callee == "parse_int":
                s = self.generate_expr(expr.args[0], context_prefix, valid_fields)
                return f"ktl_parse_int({s})"
            if expr.callee == "path_base":
                p = self.generate_expr(expr.args[0], context_prefix, valid_fields)
                return f"ktl_path_base({p})"
            if expr.callee == "path_dir":
                p = self.generate_expr(expr.args[0], context_prefix, valid_fields)
                return f"ktl_path_dir({p})"
            if expr.callee == "sb_create":
                cap = self.generate_expr(expr.args[0], context_prefix, valid_fields) if expr.args else "64"
                return f"ktl_sb_create({cap})"
            if expr.callee == "sb_append":
                sb = self.generate_expr(expr.args[0], context_prefix, valid_fields)
                val = self.generate_expr(expr.args[1], context_prefix, valid_fields)
                return f"ktl_sb_append({self.to_ptr(sb)}, {val})"
            if expr.callee == "sb_append_char":
                sb = self.generate_expr(expr.args[0], context_prefix, valid_fields)
                c = self.generate_expr(expr.args[1], context_prefix, valid_fields)
                return f"ktl_sb_append_char({self.to_ptr(sb)}, {c})"
            if expr.callee == "sb_build":
                sb = self.generate_expr(expr.args[0], context_prefix, valid_fields)
                return f"ktl_sb_build({self.to_ptr(sb)})"
            if expr.callee == "sb_free":
                sb = self.generate_expr(expr.args[0], context_prefix, valid_fields)
                return f"ktl_sb_free({self.to_ptr(sb)})"
            # Check if this function takes named args or has defaults
            arg_list = []
            target_func = self.functions.get(expr.callee)
            if target_func:
                # Map positional and named args
                passed_args: Dict[str, str] = {}
                for i, a in enumerate(expr.args):
                    if i < len(target_func.params):
                        val_c = self.generate_expr(a, context_prefix, valid_fields)
                        param = target_func.params[i]
                        if param.is_ref and not val_c.startswith("&") and not val_c.startswith("*"):
                            val_c = f"&{val_c}"
                        passed_args[param.name] = val_c
                for name, a in expr.named_args:
                    passed_args[name] = self.generate_expr(a, context_prefix, valid_fields)

                for p in target_func.params:
                    if p.name in passed_args:
                        arg_list.append(passed_args[p.name])
                    elif p.default_value is not None:
                        arg_list.append(self.generate_expr(p.default_value))
                    else:
                        arg_list.append("0")
            else:
                for a in expr.args:
                    arg_list.append(self.generate_expr(a, context_prefix, valid_fields))
            
            args_str = ", ".join(arg_list)
            return f"{expr.callee}({args_str})"

        if isinstance(expr, ChainedCall):
            # ChainedCall: idkbro(timeout = 10).start()
            self.chain_var_counter += 1
            chain_var = f"_chain_{self.chain_var_counter}"
            base_func_name = expr.base_call.callee
            base_call_code = self.generate_expr(expr.base_call, context_prefix, valid_fields)
            
            lines = [f"{base_func_name}_ctx {chain_var} = {base_call_code}"]
            for link in expr.chain:
                method_c_name = f"{base_func_name}_{link.callee}"
                link_args = [f"&{chain_var}"]
                for a in link.args:
                    link_args.append(self.generate_expr(a, context_prefix, valid_fields))
                lines.append(f"{method_c_name}({', '.join(link_args)})")
            
            return "({" + "; ".join(lines) + ";})"

        if isinstance(expr, StructInit):
            field_inits = []
            f_refs = self.struct_field_refs.get(expr.struct_name, {})
            for f_name, f_val in expr.fields:
                val_c = self.generate_expr(f_val, context_prefix, valid_fields)
                if f_refs.get(f_name, False) and not val_c.startswith("&") and not val_c.startswith("*"):
                    val_c = f"&{val_c}"
                field_inits.append(f".{f_name} = {val_c}")
            inits_str = ", ".join(field_inits)
            return f"({expr.struct_name}){{ {inits_str} }}"

        if isinstance(expr, MemberAccess):
            if isinstance(expr.target, Identifier) and expr.target.name in self.enums:
                return f"{expr.target.name}_{expr.member}"
            tgt = self.generate_expr(expr.target, context_prefix, valid_fields)
            is_ptr = False
            if isinstance(expr.target, Identifier) and expr.target.name in self.ref_params:
                is_ptr = True
            arrow = "->" if is_ptr else "."
            access_str = f"{tgt}{arrow}{expr.member}"
            tgt_struct = None
            if isinstance(expr.target, Identifier):
                tgt_struct = self.symbol_types.get(expr.target.name)
            if tgt_struct and tgt_struct in self.struct_field_refs:
                if self.struct_field_refs[tgt_struct].get(expr.member, False):
                    access_str = f"(*{access_str})"
            return access_str

        if isinstance(expr, OrExpr):
            l_code = self.generate_expr(expr.left, context_prefix, valid_fields)
            if expr.is_return:
                return f"({{ __auto_type _v = {l_code}; if (!_v) return; _v; }})"
            elif expr.is_panic:
                return f"({{ __auto_type _v = {l_code}; if (!_v) ktl_panic(\"{expr.panic_msg}\"); _v; }})"
            else:
                fb_code = self.generate_expr(expr.fallback_expr, context_prefix, valid_fields)
                return f"({{ __auto_type _v = {l_code}; _v ? _v : ({fb_code}); }})"

        return ""
